//go:build darwin

package clipboard

import (
	"bytes"
	"context"
	"os/exec"
	"strings"
)

type darwinBackend struct{}

func newPlatformBackend() Backend {
	return &darwinBackend{}
}

func (b *darwinBackend) Capabilities() Capabilities {
	return Capabilities{
		Supported:           true,
		BackendName:         "macos (NSPasteboard)",
		ConcealedFilterSafe: true,
	}
}

const darwinInspectScript = `
ObjC.import('AppKit');
var pb = $.NSPasteboard.generalPasteboard;
var types = ObjC.unwrap(pb.types);
var blocked = false;
if (types) {
  for (var i = 0; i < types.length; i++) {
    var t = ObjC.unwrap(types[i]);
    if (t === 'org.nspasteboard.ConcealedType' ||
        t === 'org.nspasteboard.TransientType' ||
        t === 'org.nspasteboard.AutoGeneratedType') {
      blocked = true;
      break;
    }
  }
}
blocked ? 'CONCEALED' : 'OK';
`

func (b *darwinBackend) Read(ctx context.Context) (Snapshot, error) {
	statusOut, err := exec.CommandContext(ctx, "osascript", "-l", "JavaScript", "-e", darwinInspectScript).Output()
	if err == nil && strings.TrimSpace(string(statusOut)) == "CONCEALED" {
		return Snapshot{Concealed: true, Reason: "macOS concealed pasteboard type"}, nil
	}
	out, err := exec.CommandContext(ctx, "pbpaste").Output()
	if err != nil {
		return Snapshot{}, nil
	}
	return Snapshot{Text: string(out)}, nil
}

func (b *darwinBackend) WriteText(ctx context.Context, text string) error {
	cmd := exec.CommandContext(ctx, "pbcopy")
	cmd.Stdin = bytes.NewBufferString(text)
	return cmd.Run()
}
