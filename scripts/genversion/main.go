// Command genversion stamps the release version into the Flitnix binary at
// build time.
//
// Wails runs it as a pre-build hook, so `wails build` always compiles the
// version of the tag being built instead of a stale literal committed to the
// tree. The version is resolved from, in order:
//
//  1. FLITNIX_VERSION
//  2. GITHUB_REF_NAME when it looks like a release tag
//  3. the nearest git tag, via `git describe --tags --abbrev=0`
//
// With -print it writes nothing and only prints the resolved version, which
// scripts/package-linux.sh uses to name artifacts.
package main

import (
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

// semverRE requires at least major.minor, so a bare tag like "1" or a stray
// branch name is never mistaken for a release version.
var semverRE = regexp.MustCompile(`^[0-9]+(\.[0-9]+)+(-[0-9A-Za-z.+~-]+)?$`)

func main() {
	printOnly := flag.Bool("print", false, "print the resolved version and exit without writing files")
	flag.Parse()

	root, err := moduleRoot()
	if err != nil {
		fail(err)
	}

	version, err := resolveVersion(root)
	if err != nil {
		fail(err)
	}

	if !*printOnly {
		if err := writeVersionFile(root, version); err != nil {
			fail(err)
		}
	}

	if *printOnly && version != "" {
		fmt.Println(version)
	}
}

func fail(err error) {
	fmt.Fprintf(os.Stderr, "genversion: %v\n", err)
	os.Exit(1)
}

// resolveVersion returns the version to stamp, or "" when none can be
// resolved and the in-tree fallback should stay in effect. An explicitly
// requested version that is not a valid semver is an error, not a silent
// fallback, so a mistyped release is never shipped under the wrong number.
func resolveVersion(root string) (string, error) {
	if raw := strings.TrimSpace(os.Getenv("FLITNIX_VERSION")); raw != "" {
		version, ok := normalize(raw)
		if !ok {
			return "", fmt.Errorf("FLITNIX_VERSION %q is not a semantic version", raw)
		}
		return version, nil
	}

	if version, ok := normalize(os.Getenv("GITHUB_REF_NAME")); ok {
		return version, nil
	}

	tag, err := nearestTag(root)
	if err != nil {
		// Not a git checkout or no tags: fall back to the committed literal.
		return "", nil
	}
	version, ok := normalize(tag)
	if !ok {
		return "", nil
	}
	return version, nil
}

// normalize strips a leading "v" and validates the semantic version shape,
// reporting whether the input is usable.
func normalize(raw string) (string, bool) {
	candidate := strings.TrimPrefix(strings.TrimSpace(raw), "v")
	if i := strings.IndexAny(candidate, " \t\r\n"); i >= 0 {
		candidate = candidate[:i]
	}
	if !semverRE.MatchString(candidate) {
		return "", false
	}
	return candidate, true
}

func nearestTag(root string) (string, error) {
	out, err := exec.Command("git", "-C", root, "describe", "--tags", "--abbrev=0").Output()
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(out)), nil
}

// moduleRoot walks up from the working directory to the directory holding
// go.mod. Wails runs hooks from the build output directory, so the working
// directory is not the module root.
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("go.mod not found in any parent directory")
		}
		dir = parent
	}
}

func writeVersionFile(root, version string) error {
	target := filepath.Join(root, "internal", "version", "version_generated.go")

	if version == "" {
		// No tag or explicit version: keep the in-tree fallback.
		if err := os.Remove(target); err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
		return nil
	}

	src := fmt.Sprintf(`// Code generated by scripts/genversion; DO NOT EDIT.

package version

func init() {
	Version = %q
}
`, version)

	formatted, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("format generated version file: %w", err)
	}

	if err := os.WriteFile(target, formatted, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", target, err)
	}
	return nil
}
